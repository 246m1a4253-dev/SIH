/**
 * Gets translated text for a key or falls back gracefully
 */
export const getTranslation = (key, langCode = 'en', defaultVal = '') => {
  if (TRANSLATIONS[key] && TRANSLATIONS[key][langCode]) {
    return TRANSLATIONS[key][langCode];
  }
  if (TRANSLATIONS[key] && TRANSLATIONS[key]['hi'] && langCode !== 'en') {
    return TRANSLATIONS[key]['hi'];
  }
  if (TRANSLATIONS[key] && TRANSLATIONS[key]['en']) {
    return TRANSLATIONS[key]['en'];
  }
  return defaultVal || key;
};
